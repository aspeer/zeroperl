import {readFileSync, statSync} from 'node:fs';
const [tarball, inventory] = process.argv.slice(2);
const [pack] = JSON.parse(readFileSync(inventory, 'utf8'));
const wasm = pack.files.filter(file => file.path.endsWith('.wasm'));
if (wasm.length !== 1 || wasm[0].path.includes('reactor')) throw Error('npm must contain exactly one production WASM');
if (pack.files.some(file => file.path.endsWith('.tar.gz') || /reactor/i.test(file.path))) throw Error('Diagnostic artifacts must not ship in npm');
if (pack.files.some(file => file.path.startsWith('licenses/'))) throw Error('Full licence evidence belongs in the GitHub Release');
const notices = pack.files.find(file => file.path === 'THIRD-PARTY-LICENSES.txt');
if (!notices || notices.size <= 0 || notices.size > 500_000) throw Error('Missing or oversized reviewed runtime notices');
if (!pack.files.some(file => file.path === 'THIRD-PARTY-NOTICES.md')) throw Error('Missing third-party licence reference');
const bytes = statSync(tarball).size;
if (bytes > 6_000_000) throw Error(`npm archive exceeds the 6 MB budget: ${bytes} bytes`);
console.log(`Lean npm archive verified: ${bytes} bytes, one production WASM, reviewed runtime notices`);
